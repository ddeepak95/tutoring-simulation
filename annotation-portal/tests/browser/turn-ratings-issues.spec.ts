test('desktop rating panels fit the remaining viewport without page scrolling', async ({ page }) => {
  const state = await backend(page); state.assignments[0].task_type = 'rate'; state.assignments[0].annotations = [];
  await page.setViewportSize({ width: 1440, height: 900 });
  await login(page, 'alice'); await page.getByRole('region', { name: 'Rate tutor turns' }).locator('.assignment-row').click();
  await expect(page.getByRole('complementary', { name: 'Tutor turn ratings' })).toBeVisible();
  const layout = await page.evaluate(() => {
    const transcript = document.querySelector('.rating-workspace .document')!.getBoundingClientRect();
    const panel = document.querySelector('.turn-ratings-panel')!.getBoundingClientRect();
    return { transcriptHeight: transcript.height, panelHeight: panel.height, transcriptBottom: transcript.bottom, panelBottom: panel.bottom, pageHeight: document.documentElement.scrollHeight, viewportHeight: window.innerHeight };
  });
  expect(Math.abs(layout.transcriptHeight - layout.panelHeight)).toBeLessThan(2);
  expect(layout.transcriptBottom).toBeLessThanOrEqual(layout.viewportHeight);
  expect(layout.panelBottom).toBeLessThanOrEqual(layout.viewportHeight);
  expect(layout.pageHeight).toBeLessThanOrEqual(layout.viewportHeight);
});

