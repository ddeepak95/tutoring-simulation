import { expect, test } from '@playwright/test';
import { backend, ids, login } from './mock';

test('topic page groups languages into separate collapsible provider accordions', async ({ page }) => {
  const state = await backend(page);
  const original = state.documents[0] as any;
  Object.assign(original, { language: 'ta', topic_id: 'evaporation', generic_topic_name: 'Evaporation' });
  Object.assign(original.transcript, { provider: 'GPT', topic_id: 'evaporation', conversation_id: ids.doc });
  state.documents.push({ ...structuredClone(original), id: 'english', language: 'en', transcript: { ...structuredClone(original.transcript), conversation_id: 'english' } });
  state.documents.push({ ...structuredClone(original), id: 'chatgpt', transcript: { ...structuredClone(original.transcript), conversation_id: 'chatgpt', provider: 'ChatGPT' } });
  await login(page, 'admin', { expandTopic: false });
  await page.locator('.topic-link').click();
  const providers = page.locator('.provider-accordion');
  await expect(providers).toHaveCount(2);
  const gpt = providers.filter({ has: page.locator('summary strong').filter({ hasText: /^GPT$/ }) });
  const chatgpt = providers.filter({ has: page.locator('summary strong').filter({ hasText: /^ChatGPT$/ }) });
  await expect(gpt.locator('.provider-language-link')).toHaveCount(2);
  await expect(gpt.locator('.provider-language-link').first()).toBeHidden();
  await chatgpt.locator('summary').first().click();
  await expect(chatgpt).toHaveAttribute('open', '');
  await gpt.locator('summary').first().focus(); await page.keyboard.press('Enter');
  await expect(gpt).toHaveAttribute('open', '');
  await expect(chatgpt).not.toHaveAttribute('open', '');
  await expect(gpt.locator('.provider-language-link strong')).toHaveText(['English', 'Tamil']);
  await gpt.locator('.provider-language-link').filter({ hasText: 'Tamil' }).click();
  await expect(page).toHaveURL('/topics/evaporation/conversations/GPT/ta');
  await page.goBack();
  await expect(gpt).toHaveAttribute('open', '');
  await expect(chatgpt).not.toHaveAttribute('open', '');
  await page.reload();
  await expect(gpt).toHaveAttribute('open', '');
  await gpt.locator('.provider-language-link').filter({ hasText: 'Tamil' }).click();
  await page.getByRole('navigation', { name: 'Conversation navigation' }).getByRole('link', { name: 'Evaporation', exact: true }).click();
  await expect(gpt).toHaveAttribute('open', '');
  await gpt.locator('summary').first().click();
  await page.reload();
  await expect(gpt).not.toHaveAttribute('open', '');
});

test('topic entries open tries with linked translations, including refresh and translation management', async ({ page }) => {
  const state = await backend(page);
  const original = state.documents[0] as any;
  Object.assign(original, { topic_id: 'evaporation', generic_topic_name: 'Evaporation', language: 'ta', created_at: '2026-10-01T00:00:00Z' });
  Object.assign(original.transcript, { conversation_id: original.id, topic_id: 'evaporation', provider: 'GPT', access_type: 'API' });
  const second = '00000000-0000-4000-8000-000000000080';
  const translation = '00000000-0000-4000-8000-000000000081';
  state.documents.push({ ...structuredClone(original), id: second, created_at: '2026-10-02T00:00:00Z', transcript: { ...structuredClone(original.transcript), conversation_id: second } });
  state.documents.push({ ...structuredClone(original), id: translation, label: 'English translation', language: 'en', source_conversation_id: ids.doc, transcript: { ...structuredClone(original.transcript), conversation_id: translation, source_conversation_id: ids.doc, provider: 'Gemini' } });
  await login(page, 'admin', { expandTopic: false });
  await expect(page.locator('.provider-language-link')).toHaveCount(0);
  await expect(page.locator('.progress')).toHaveCount(0);
  await page.locator('.topic-link').click();
  await expect(page).toHaveURL('/topics/evaporation');
  await page.reload();
  const entry = page.locator('.provider-language-link');
  await expect(entry).toHaveCount(1);
  await expect(page.locator('.provider-accordion>summary')).toContainText('GPT'); await expect(entry).toContainText('Tamil'); await expect(entry).toContainText('2 tries'); await expect(entry).toContainText('1 translation');
  await expect(page.locator('.conversation-table')).toHaveCount(0);
  await page.locator('.provider-accordion>summary').first().click();
  await entry.click();
  await expect(page).toHaveURL(/\/topics\/evaporation\/conversations\/GPT\/ta$/);
  await expect(page.getByRole('heading', { name: 'GPT / Tamil' })).toBeVisible();
  await expect(page.locator('.conversation-table tbody tr')).toHaveCount(2);
  const first = page.locator(`[data-conversation-id="${ids.doc}"]`);
  await expect(first).toContainText('Try 1');
  await expect(first.locator(`[data-translation-id="${translation}"]`)).toContainText('English translation');
  await expect(first.locator(`[data-translation-id="${translation}"]`).getByRole('link', { name: 'Label', exact: true })).toHaveAttribute('href', `/conversations/${translation}/labeling`);
  await expect(page.locator(`[data-conversation-id="${translation}"]`)).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.conversation-table tbody tr')).toHaveCount(2);
  await page.getByRole('button', { name: 'Assign users for English translation', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'GPT / Tamil' })).toBeVisible();
  await page.getByRole('link', { name: 'All topics', exact: true }).click();
  await expect(page).toHaveURL('/');
  await expect(page.locator('.topic-link')).toHaveCount(1);
  expect(state.saves).toBe(0);
});
